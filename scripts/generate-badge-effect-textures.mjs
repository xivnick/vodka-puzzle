// Offline only. The browser downloads five reusable white/alpha sprite sheets.
import sharp from 'sharp';
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {EFFECTS,FPS,SIZE,frameSvg} from './lib/badge-effect-frames.mjs';
const root=new URL('../',import.meta.url),directory=new URL('public/images/badge-effect-textures/',root),manifest={};
await fs.mkdir(directory,{recursive:true});
let bytes=0,decodedBytes=0;
for(const [effect,{duration}] of Object.entries(EFFECTS)){
 const frames=Math.round(duration*FPS),columns=Math.min(8,frames),rows=Math.ceil(frames/columns),composites=[];
 for(let frame=0;frame<frames;frame++){
  const input=await sharp(Buffer.from(frameSvg(effect,frame/FPS))).png().toBuffer();
  composites.push({input,left:frame%columns*SIZE,top:Math.floor(frame/columns)*SIZE});
 }
 const image=await sharp({create:{width:SIZE*columns,height:SIZE*rows,channels:4,background:{r:255,g:255,b:255,alpha:0}}}).composite(composites).png({compressionLevel:9,palette:true,quality:100,dither:0}).toBuffer();
 const hash=createHash('sha256').update(image).digest('hex').slice(0,12),file=`${effect}.${hash}.png`;
 await fs.writeFile(new URL(file,directory),image);
 manifest[effect]={src:`/images/badge-effect-textures/${file}`,frames,columns,rows,duration,size:SIZE,bytes:image.length};
 bytes+=image.length;decodedBytes+=SIZE*SIZE*columns*rows*4;
}
await fs.writeFile(new URL('src/data/badge-effect-textures.js',root),'// Generated by scripts/generate-badge-effect-textures.mjs\nexport const badgeEffectTextures='+JSON.stringify(manifest,null,2)+';\n');
console.log(JSON.stringify({effects:5,fps:FPS,bytes,decodedBytes,manifest},null,2));
