// Native CSS step animations move one static atlas per complex effect.
import sharp from 'sharp';
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {EFFECTS,frameSvg} from './lib/badge-effect-frames.mjs';
const root=new URL('../',import.meta.url),directory=new URL('public/images/badge-transform-textures/',root);
const fps=30,size=64,manifest={};let css='/* Generated by scripts/generate-badge-transform-textures.mjs. */\n';
await fs.mkdir(directory,{recursive:true});
for(const effect of ['foil','interference','lenticular']){
 const duration=EFFECTS[effect].duration,frames=Math.round(duration*fps),unique=[],seen=new Map(),timeline=[];
 for(let frame=0;frame<frames;frame++){
  const raw=await sharp(Buffer.from(frameSvg(effect,frame/fps,size))).ensureAlpha().raw().toBuffer();
  const alpha=Buffer.alloc(size*size);for(let i=0;i<alpha.length;i++)alpha[i]=raw[i*4+3];
  const key=createHash('sha256').update(alpha).digest('hex');
  if(!seen.has(key)){seen.set(key,unique.length);unique.push(await sharp(raw,{raw:{width:size,height:size,channels:4}}).png().toBuffer());}
  timeline.push(seen.get(key));
 }
 const columns=Math.min(16,unique.length),rows=Math.ceil(unique.length/columns);
 const image=await sharp({create:{width:size*columns,height:size*rows,channels:4,background:{r:255,g:255,b:255,alpha:0}}})
  .composite(unique.map((input,index)=>({input,left:index%columns*size,top:Math.floor(index/columns)*size})))
  .png({compressionLevel:9,palette:true,quality:100,dither:0}).toBuffer();
 const hash=createHash('sha256').update(image).digest('hex').slice(0,12),file=`${effect}.${hash}.png`;
 await fs.writeFile(new URL(file,directory),image);
 manifest[effect]={src:`/images/badge-transform-textures/${file}`,fps,frames,packedFrames:unique.length,columns,rows,size,duration,bytes:image.length,timeline};
 const transform=index=>`translate(${-(index%columns)/columns*100}%,${-Math.floor(index/columns)/rows*100}%)`;
 css+=`@keyframes badge-frames-${effect}{`;
 for(let frame=0;frame<frames;frame++)if(frame===0||timeline[frame]!==timeline[frame-1])css+=`${Math.floor(frame/frames*100*1e10)/1e10}%{transform:${transform(timeline[frame])}}`;
 css+=`100%{transform:${transform(timeline.at(-1))}}}\n`;
}
await fs.writeFile(new URL('src/data/badge-transform-textures.js',root),'// Generated by scripts/generate-badge-transform-textures.mjs\nexport const badgeTransformTextures='+JSON.stringify(manifest,null,2)+';\n');
await fs.writeFile(new URL('src/styles/badge-effect-transform-frames.css',root),css);
console.log(JSON.stringify(Object.fromEntries(Object.entries(manifest).map(([effect,{timeline,...item}])=>[effect,item])),null,2));
